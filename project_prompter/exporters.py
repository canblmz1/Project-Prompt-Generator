"""Export analysis results to markdown and JSON files."""

from __future__ import annotations

import json
from dataclasses import asdict
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional

from .models import ProjectAnalysis, ScanOptions


def export_all(
    analysis: ProjectAnalysis,
    prompts: Dict[str, str],
    options: ScanOptions,
) -> List[Path]:
    """
    Export all output files for a scan.

    Returns a list of created file paths.
    """
    output_dir = options.output_path
    output_dir.mkdir(parents=True, exist_ok=True)

    prompts_dir = output_dir / "prompts"
    prompts_dir.mkdir(parents=True, exist_ok=True)

    created: List[Path] = []

    # Core markdown files
    created.append(_write(output_dir / "project_summary.md", _build_project_summary_md(analysis)))
    created.append(_write(output_dir / "file_tree.md", _build_file_tree_md(analysis)))
    created.append(_write(output_dir / "tech_stack.md", _build_tech_stack_md(analysis)))
    created.append(_write(output_dir / "risk_notes.md", _build_risk_notes_md(analysis)))
    created.append(_write(output_dir / "redaction_report.md", _build_redaction_report_md(analysis)))

    # Scan report JSON
    created.append(_write(output_dir / "scan_report.json", _build_scan_report_json(analysis, options)))

    # Prompt files
    for model_name, prompt_content in prompts.items():
        prompt_path = prompts_dir / f"{model_name}_prompt.md"
        created.append(_write(prompt_path, prompt_content))

    return created


def _write(path: Path, content: str) -> Path:
    """Write content to a file and return the path."""
    path.write_text(content, encoding="utf-8")
    return path


